pub fn helvetica_width(byte: u8, bold: bool) -> u16 {
    if (32..=126).contains(&byte) {
        let table = if bold { &BOLD } else { &REGULAR };
        table[(byte - 32) as usize]
    } else {
        556
    }
}

/// يحوّل محرفًا إلى بايت WinAnsi إن أمكن. `None` يعني أن الخط القياسي لا يرسمه.
pub fn win_ansi(c: char) -> Option<u8> {
    let code = c as u32;
    match code {
        0x20..=0x7E | 0xA0..=0xFF => Some(code as u8),
        0x2022 => Some(0x95),
        0x2013 => Some(0x96),
        0x2014 => Some(0x97),
        0x2018 => Some(0x91),
        0x2019 => Some(0x92),
        0x201C => Some(0x93),
        0x201D => Some(0x94),
        0x20AC => Some(0x80),
        0x2026 => Some(0x85),
        _ => None,
    }
}

/// العكس: بايت WinAnsi إلى محرف، لاستخراج النصّ عند التحقق.
pub fn from_win_ansi(b: u8) -> char {
    match b {
        0x95 => '\u{2022}',
        0x96 => '\u{2013}',
        0x97 => '\u{2014}',
        0x91 => '\u{2018}',
        0x92 => '\u{2019}',
        0x93 => '\u{201C}',
        0x94 => '\u{201D}',
        0x80 => '\u{20AC}',
        0x85 => '\u{2026}',
        b => b as char,
    }
}
