// عيّنة W5: ابن يبقى حيًّا عمدًا، ويُعلن استعداده مرة واحدة.
//
// وجودها ضرورة قياس لا زينة. W4 أثبت أن الـJob مضبوط على القتل عند الإغلاق،
// وأن المنفّذ يكمل ويخرج. ما لم يُقَس قط هو الحالة التي يهمّ فيها الإيقاف:
// ابن ما زال يعمل، ثم يُغلق الـJob، فيموت. لقياس ذلك يلزم ابن لا ينتهي من
// تلقاء نفسه.
//
// هذا الملف ليس مسار تنفيذ: لا يستورد شيئًا، ولا يقرأ ملفًا ولا يكتب ملفًا ولا
// يفتح شبكة، ولا يمكن أن يُحدث أثرًا. كل ما يفعله أن يُعلن إقلاعه ثم يبقى حيًّا
// حتى يُنهيه من يملكه. ويُدرَّج في نطاق كود التشغيل بنفس الطريقة التي يُدرَّج بها
// المنفّذ الحقيقي، فالمسار الذي يُقاس هو المسار نفسه: إطلاق معلّق، ضمٌّ إلى Job
// قبل الاستئناف، ثم استئناف.
//
// ── عقد الاستعداد ───────────────────────────────────────────────────────────
// وثيقة واحدة، مبنيّة بنيويًا، منتهية بسطر جديد، على المخرج القياسي — وهو مقبض
// موروث بقائمة مقابض صريحة، منشأ من المُقيس، ومُغلق في تنظيفه. لا مقبض جديد،
// ولا كائن نواة مُسمّى، ولا انتظار زمني في أي طرف.
//
// وتُوقَّع الوثيقة بعدد استعمال واحد (nonce) يمرّره المُقيس في سطر الأوامر. بلا
// هذا التوقيع تكون «READY» جملةً يمكن أن تأتي من مخرج قديم أو من عمليةٍ أخرى؛
// ومعه تكون إعلانًا من هذا الابن بعينه، في هذا القياس بعينه.
//
// وما تعنيه الوثيقة تحديدًا: أن مفسّر العقدة أقلع، وحمّل هذه الوحدة، ونفّذها
// حتى هذا السطر. هي إثبات إقلاع ناجح، لا مرور زمن.

/** توقيع القياس كما مرّره المُقيس. غيابه يجعل الوثيقة غير مطابقة، لا مقبولة. */
const nonce: string = process.argv[2] ?? "";

/** وثيقة الاستعداد. مرة واحدة، ولا يُكتب على المخرج القياسي شيء بعدها. */
const ready: string = JSON.stringify({
  protocol: "polaris.w5.readiness",
  version: 1,
  role: "w5-hold-child",
  state: "READY",
  pid: process.pid,
  nonce,
});
process.stdout.write(`${ready}\n`);

// لا خروج من تلقاء النفس. الإنهاء يأتي من إغلاق الـJob وحده.
setInterval((): void => {
  // متعمَّد الفراغ: الغرض إبقاء حلقة الأحداث حيّة، لا إنجاز عمل.
}, 3600000);
