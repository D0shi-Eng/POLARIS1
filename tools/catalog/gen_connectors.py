def color(name):
    h = int(hashlib.md5(name.encode()).hexdigest()[:6], 16) % 360
    r, g, b = colorsys.hls_to_rgb(h / 360, 0.42, 0.55)
    return "#%02x%02x%02x" % (int(r * 255), int(g * 255), int(b * 255))

def mark(name):
    words = [w for w in name.replace("(", " ").split() if w[0].isalnum()]
    return (words[0][0] + (words[1][0] if len(words) > 1 else (words[0][1] if len(words[0]) > 1 else ""))).upper() if words else "?"

